// Builds reviewable SQL only. Never connects to or changes a database.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const files = ['catalyst-schema.sql', 'catalyst-seed.sql', 'catalyst-generated.sql', 'catalyst-generation-v2.sql'];

function buildInstall() {
  const preflight = fs.readFileSync(path.join(root, 'sql', 'catalyst-preflight.sql'), 'utf8').trim().replace(/;$/, '');
  const header = `-- Generated by tools/build_backend_install.cjs. Do not edit by hand.
-- FIRST INSTALL ONLY. Review docs/PHASE5E_BACKEND_READINESS.md before use.
-- One transaction: schema, public grammar seed, grants/RLS and paused quota.
-- Refuses an existing/partial Catalyst installation. Never use this to upgrade.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
select pg_advisory_xact_lock(8246, 5005);
do $$
declare v_check record;
begin
  if exists (select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace
      where n.nspname='public' and c.relname like 'catalyst\\_%' escape '\\')
    or exists (select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace
      where n.nspname='public' and p.proname like 'catalyst\\_%' escape '\\') then
    raise exception 'Existing Catalyst objects: stop and prepare an additive upgrade instead';
  end if;
  if to_regprocedure('auth.uid()') is null or to_regprocedure('public.kg_chart_is_allowed()') is null
    or to_regclass('public.kg_chart_settings') is null then
    raise exception 'Missing source prerequisites: run catalyst-preflight.sql first';
  end if;
  for v_check in
${preflight}
  loop
    if v_check.status='BLOCKED' then
      raise exception 'Source preflight failed: % (%)', v_check.check_name, v_check.detail;
    end if;
  end loop;
  if exists (select 1 from public.kg_chart_settings
      where key='catalyst_daily_limit' and value not in ('0'::jsonb, '"0"'::jsonb)) then
    raise exception 'Existing nonzero/invalid Catalyst limit: review the setting before installing';
  end if;
end $$;
`;
  const body = files.map(file => {
    const source = fs.readFileSync(path.join(root, 'sql', file), 'utf8');
    // Only these repository-owned scripts are accepted; remove their outer
    // transactions so an error cannot leave a partially installed backend.
    const transactions = source.match(/^(?:begin|commit);\s*$/gm) || [];
    if (transactions.length !== (file === 'catalyst-seed.sql' || file === 'catalyst-generation-v2.sql' ? 2 : 0)) {
      throw new Error(`Unexpected transaction structure in ${file}`);
    }
    return `\n-- Source: sql/${file}\n` + source.replace(/^(?:begin|commit);\s*$/gm, '');
  }).join('\n');
  return header + body + `
-- A deployment must explicitly enable its agreed request limit after acceptance.
insert into public.kg_chart_settings(key,value) values ('catalyst_daily_limit','0'::jsonb)
  on conflict (key) do nothing;
commit;
`;
}

if (require.main === module) {
  const output = path.join(root, 'sql', 'catalyst-initial-install.sql');
  const sql = buildInstall();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== sql) {
      throw new Error('Installation bundle is stale; run npm run prepare:backend');
    }
    console.log('Installation bundle matches its sources.');
  } else {
    fs.writeFileSync(output, sql);
    console.log('Prepared sql/catalyst-initial-install.sql; no database was contacted.');
  }
}
module.exports = { buildInstall };
